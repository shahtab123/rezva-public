/**
 * Build restricted-name lists from committed wordlists:
 * - shouldbee/reserved-usernames (URL-collision slugs → hard reserved)
 * - abaron/disallowed-usernames en.brands (brand labels → protected dictionary)
 * - crypto-brands.txt (exchanges, wallets, cards, DeFi → protected dictionary)
 */
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const dataDir = join(root, "registry", "data");

function readLines(name) {
  return readFileSync(join(dataDir, name), "utf8")
    .split(/\r?\n/)
    .map((line) => line.trim().toLowerCase())
    .filter((line) => line && !line.startsWith("#"));
}

const CORE_HARD = ["admin", "support", "system", "api", "official", "rezva"];

const FINANCE_EXTRA = [
  "bkash",
  "nagad",
  "pathao",
  "centralbank",
  "bank",
  "mastercard",
  "visa",
  "stripe",
  "paypal",
];

const GOVERNMENT_EXTRA = ["government", "gov", "police"];

const PLATFORM_EXTRA = ["telegram", "discord", "whatsapp"];

const BRAND_VARIANTS = ["coca-cola", "cocacola", "twittr"];

const shouldbee = readLines("shouldbee-reserved-usernames.txt");
const abaronBrands = readLines("abaron-en-brands.txt");
const cryptoBrands = readLines("crypto-brands.txt");

const cryptoSet = new Set(cryptoBrands);
const financeSet = new Set(FINANCE_EXTRA);
const governmentSet = new Set(GOVERNMENT_EXTRA);
const platformSet = new Set(PLATFORM_EXTRA);

const allNames = new Set([
  ...abaronBrands,
  ...cryptoBrands,
  ...FINANCE_EXTRA,
  ...GOVERNMENT_EXTRA,
  ...PLATFORM_EXTRA,
  ...BRAND_VARIANTS,
]);

function categorize(name) {
  if (cryptoSet.has(name)) return "crypto";
  if (financeSet.has(name)) return "finance";
  if (governmentSet.has(name)) return "government";
  if (platformSet.has(name)) return "platform";
  return "brand";
}

const protectedEntries = [...allNames]
  .sort((a, b) => a.localeCompare(b))
  .map((name) => ({ name, category: categorize(name) }));

const protectedNameSet = new Set(protectedEntries.map((e) => e.name));

const hardReserved = new Set(CORE_HARD);
for (const slug of shouldbee) {
  if (!protectedNameSet.has(slug)) {
    hardReserved.add(slug);
  }
}
const hardReservedSorted = [...hardReserved].sort();

const ts = `/**
 * AUTO-GENERATED by scripts/generate-restricted-names.mjs - do not edit by hand.
 * Sources:
 * - https://github.com/shouldbee/reserved-usernames (URL collision slugs)
 * - https://github.com/abaron/disallowed-usernames (en/en.brands.txt)
 * - registry/data/crypto-brands.txt (exchanges, wallets, cards, DeFi)
 */
export type ProtectedDictionaryCategory =
  | "brand"
  | "platform"
  | "finance"
  | "government"
  | "crypto"
  | "other";

export type ProtectedDictionaryEntry = {
  name: string;
  category: ProtectedDictionaryCategory;
  note?: string;
};

export const PROTECTED_NAME_DICTIONARY_SEED: ProtectedDictionaryEntry[] = ${JSON.stringify(protectedEntries, null, 2)};

export const PROTECTED_NAME_SEED = new Set<string>(PROTECTED_NAME_DICTIONARY_SEED.map((e) => e.name));

export const HARD_RESERVED_NAMES = new Set<string>(${JSON.stringify(hardReservedSorted)});

export const RESTRICTED_NAME_SOURCES = {
  shouldbee: "shouldbee/reserved-usernames",
  abaronBrands: "abaron/disallowed-usernames en.brands",
  cryptoBrands: "registry/data/crypto-brands.txt",
} as const;

export const RESTRICTED_NAME_COUNTS = {
  protectedDictionary: PROTECTED_NAME_DICTIONARY_SEED.length,
  hardReserved: HARD_RESERVED_NAMES.size,
  crypto: PROTECTED_NAME_DICTIONARY_SEED.filter((e) => e.category === "crypto").length,
} as const;
`;

const targets = [
  join(root, "registry", "src", "lib", "restricted-names-data.ts"),
  join(root, "website", "src", "lib", "restricted-names-data.ts"),
];

for (const file of targets) {
  mkdirSync(dirname(file), { recursive: true });
  writeFileSync(file, ts, "utf8");
}

const cryptoCount = protectedEntries.filter((e) => e.category === "crypto").length;
console.log(
  `Generated ${protectedEntries.length} protected (${cryptoCount} crypto) + ${hardReservedSorted.length} hard-reserved entries`,
);
